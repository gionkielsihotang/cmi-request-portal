CREATE TABLE RIWAYAT_LOG(
    idLog VARCHAR(20) NOT NULL PRIMARY KEY,
    idPengajuan VARCHAR(20) NOT NULL,
    idCMI VARCHAR(20) NOT NULL,
    aksi VARCHAR(100) NOT NULL,
    waktu DATETIME NOT NULL,
    FOREIGN KEY (idPengajuan) REFERENCES PENGAJUAN(idPengajuan),
    FOREIGN KEY (idCMI) REFERENCES CMI(idCMI));
